"""Per-run state of the literature tools (merged plan, Phase 2.4 step 4).

The AutoGen literature agent built its search tools as closures over two
values of one review: the domain keywords derived from its PICO, and the dict
``save_output`` captured the generated files into. The tools are global now, so
that state is kept per run, keyed by the ``run_id`` of the node the tools are
called in:

- ``use_pico(run_id, pico)`` sets the run's domain keywords. The literature
  agent's ``context_builder`` calls it when its node starts (Plan 3); until
  then, or without a run, the searches filter with the broad fallback list.
- ``capture()`` keeps a generated file; ``release(run_id)`` hands the run's
  files to the agent's output hook (Plan 3), which records the review through
  the Application API, and forgets them.

This is process-local memory, exactly as the closures were: run one Agent
System worker. At most ``MAX_RUNS`` runs are kept; the least recently used is
forgotten first, so runs that never reach ``release()`` (a failed review, or
any run before Plan 3 wires the hook) cannot grow the process without bound.
A run's files are lost if it is forgotten or the process dies before
``release``; the review is then regenerated by the rerun.
"""

from __future__ import annotations

from collections import OrderedDict
from dataclasses import dataclass, field
from pathlib import PurePath

from .pico import DOMAIN_KEYWORDS_FALLBACK, domain_keywords

MAX_RUNS = 256


@dataclass
class _RunState:
    keywords: list[str] = field(default_factory=lambda: list(DOMAIN_KEYWORDS_FALLBACK))
    outputs: dict[str, str] = field(default_factory=dict)


_runs: OrderedDict[str, _RunState] = OrderedDict()


def _state(run_id: str) -> _RunState:
    """The run's state, created on first use and marked most recently used."""
    state = _runs.pop(run_id, None) or _RunState()
    _runs[run_id] = state
    while len(_runs) > MAX_RUNS:
        _runs.popitem(last=False)
    return state


def use_pico(run_id: str, pico: dict[str, str] | None) -> list[str]:
    """Derive and keep the run's domain keywords; returns them."""
    state = _state(run_id)
    state.keywords = domain_keywords(pico)
    return list(state.keywords)


def keywords_for(run_id: str | None) -> list[str]:
    """The run's domain keywords, or the broad fallback list."""
    state = _runs.get(run_id) if run_id else None
    return list(state.keywords) if state else list(DOMAIN_KEYWORDS_FALLBACK)


def capture(run_id: str, filename: str, content: str) -> str:
    """Keep one generated file under its base name (a path is never kept)."""
    name = PurePath(filename.replace("\\", "/")).name
    if not name:
        raise ValueError(f"not a file name: {filename!r}")
    _state(run_id).outputs[name] = content
    return name


def captured_outputs(run_id: str) -> dict[str, str]:
    """A copy of the run's captured files."""
    state = _runs.get(run_id)
    return dict(state.outputs) if state else {}


def release(run_id: str) -> dict[str, str]:
    """The run's captured files; the run's state is forgotten."""
    state = _runs.pop(run_id, None)
    return dict(state.outputs) if state else {}
