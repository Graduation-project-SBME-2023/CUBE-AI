from ..._toolkit import is_error_result, tool
from ...common.manifests import READ_ONLY
from .. import _api
from typing import Annotated
from pydantic import Field

from ..result_shape import keep_model_id


async def masks_for_volume(volume_uid: str):
    """The masks of one volume (a list, ``[]`` when the volume has none or is
    unknown), or an ``error_result``: an unreachable API or a 5xx is never
    reported as "no mask" (L4). ``check_having_mask`` uses it too."""
    masks = await _api.get_json(f"/segmentation-masks/by-volume/{volume_uid}", on_not_found=[])
    return masks if is_error_result(masks) else keep_model_id(masks)


@tool(
    visibility={"agent", "main"},
    **READ_ONLY,
)
async def get_segmentation(
    label_uid: Annotated[str | None, Field(description="The unique identifier of the segmentation label. If provided, fetches a single detailed record. If omitted, fetches a list of all segmentations.")] = None,
    skip: Annotated[int, Field(description="Pagination offset: The number of segmentation records to skip before starting the list.")] = 0,
    limit: Annotated[int, Field(description="Pagination limit: The maximum number of segmentation records to return in one request (max 100).")] = 100
):
    """
    Retrieves segmentation label information from the database.

    Use this tool in two scenarios:
    1. To find details for a specific segmentation when you know its 'label_uid'.
    2. To browse or list multiple segmentations when no specific UID is known (uses pagination).
    """
    if label_uid is not None:
        return await _api.read(f"/segmentation-masks/{label_uid}", shape=keep_model_id)
    return await _api.read(
        "/segmentation-masks/", params={"skip": skip, "limit": limit}, shape=keep_model_id
    )
    
    

@tool(
    visibility={"agent", "main"},
    **READ_ONLY,
)
async def get_segmentation_by_volume(
    volume_uid: Annotated[str, Field(description="The unique identifier (Series Instance UID) of the image volume. This is required to fetch all segmentation labels associated with that specific volume.")]
):
    """
    Retrieves all segmentation labels associated with a specific image volume.

    Use this tool in this specific scenario:
    1. To retrieve the segmentation masks or labels for a known volume using its 'volume_uid' (e.g., "Show me the segmentations for Volume X").
    """
    masks = await masks_for_volume(volume_uid)
    return masks if is_error_result(masks) else {"data": masks}

@tool(
    visibility={"agent", "main"},
    **READ_ONLY,
)
async def get_segmentation_by_model(
    model_name: Annotated[str, Field(description="The name of the AI model. This is required to fetch all segmentation labels generated by that specific model.")]
):
    """
    Retrieves all segmentation labels generated by a specific AI model.

    Use this tool in this specific scenario:
    1. To filter segmentations based on the model that created them (e.g., "Show me all segmentations produced by Model-X").
    """
    return await _api.read(f"/segmentation-masks/by-model/{model_name}", shape=keep_model_id)
    
    
@tool(
    visibility={"agent", "main"},
    **READ_ONLY,
)
async def get_invalidate_segmentations(
    skip: Annotated[int, Field(description="Pagination offset: The number of records to skip.")] = 0,
    limit: Annotated[int, Field(description="Pagination limit: The maximum number of records to return (max 100).")] = 100
):
    """
    Retrieves a list of segmentations marked as invalid or requiring review.

    Use this tool in this specific scenario:
    1. To browse or list specific segmentations that have failed validation or need attention (uses pagination).
    """
    return await _api.read(
        "/segmentation-masks/unvalidated/",
        params={"skip": skip, "limit": limit},
        shape=keep_model_id,
    )
