"""
List available plot images from the workspace for inclusion in LaTeX reports.
"""

import json
import os
import glob
from .. import mcp
from pydantic import Field
from typing import Annotated


@mcp.tool()
async def list_workspace_plots() -> str:
    """List all plot image files (.png, .jpg) available in the workspace.

    Scans the workspace directory recursively for image files generated by
    upstream agents (e.g., ROC curves, confusion matrices, feature importance
    plots, correlation heatmaps).

    Returns a JSON object with:
      - plots: list of objects with 'filename' (basename for \\includegraphics)
               and 'source_path' (full path for reference)
      - count: total number of plots found

    Use the 'filename' value directly in \\includegraphics{filename} — the
    latex_to_pdf tool automatically copies all workspace images into the
    compilation directory.
    """
    workspace_folder = os.environ.get("WORKSPACE_DIR", "")
    if not workspace_folder or not os.path.isdir(workspace_folder):
        return json.dumps({
            "plots": [],
            "count": 0,
            "message": "No workspace directory found.",
        }, indent=2)

    plots = []
    seen_basenames = set()
    for ext in ("*.png", "*.jpg", "*.jpeg"):
        for img_path in glob.glob(
            os.path.join(workspace_folder, "**", ext), recursive=True
        ):
            basename = os.path.basename(img_path)
            if basename not in seen_basenames:
                seen_basenames.add(basename)
                # Determine which agent/stage produced this plot
                rel_path = os.path.relpath(img_path, workspace_folder)
                plots.append({
                    "filename": basename,
                    "relative_path": rel_path,
                    "source_path": img_path,
                })

    # Sort by relative path for readability
    plots.sort(key=lambda p: p["relative_path"])

    return json.dumps({
        "plots": plots,
        "count": len(plots),
    }, indent=2)
