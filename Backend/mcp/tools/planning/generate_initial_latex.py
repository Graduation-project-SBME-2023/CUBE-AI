"""
Generate Initial LaTeX MCP Tool

Generates a minimal LaTeX document containing an Introduction and a
Literature Review section from the planner's saved literature context.
This tool also attempts to compile the LaTeX using the existing
`latex_to_pdf` helper and writes a structured agent output using
`write_agent_output` so the frontend can receive `latex_output` events.

This is intentionally conservative: it produces a simple LaTeX file
using the `literature_context.json` saved in the workspace.
"""
import os
import json
import asyncio
from typing import Annotated
from pydantic import Field

from .. import mcp
from tool_logging import ToolEvent, log_tool_state, TextPayload

# Import helper tools from sibling modules (call their functions directly)
from ..latex.latex_to_pdf import latex_to_pdf
from ..agent_output import write_agent_output
from ..agent_output import WriteAgentOutputInput

WORKSPACE_DIR = os.environ.get("WORKSPACE_DIR", os.path.abspath(os.path.join(os.getcwd(), "workspace")))


@mcp.tool(
    name="generate_initial_latex",
    annotations={
        "title": "Generate Initial LaTeX (Introduction + Literature Review)",
    },
)
async def generate_initial_latex(section_list: Annotated[str, Field(description="Comma separated list of sections to include (default: introduction,literature_review)")] = "introduction,literature_review") -> str:
    """Generate an initial LaTeX document and attempt to compile it.

    Returns a JSON string with keys: status, latex_text, pdf_path, latex_pdf
    """
    try:
        payload = TextPayload(message="Generating initial LaTeX from literature context...")
        log_tool_state(ToolEvent('tool_started', 'text', payload))

        lit_path = os.path.join(WORKSPACE_DIR, "literature_context.json")
        if not os.path.exists(lit_path):
            msg = "No literature context found in workspace."
            log_tool_state(ToolEvent('error', 'text', TextPayload(message=msg)))
            return json.dumps({"status": "error", "message": msg})

        with open(lit_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        knowledge = data.get("knowledge_base", "")
        sources = data.get("sources_guide", "")
        hypothesis = data.get("hypothesis", {})

        # Build a simple LaTeX document
        title = hypothesis.get("title", "Study Report") if isinstance(hypothesis, dict) else "Study Report"
        intro = "This document contains the initial Introduction and Literature Review generated by the planner."
        if isinstance(hypothesis, dict):
            hyp_text = hypothesis.get("text", "") or hypothesis.get("hypothesis", "")
            if hyp_text:
                intro += "\\\n\\\nHypothesis: " + hyp_text

        sections = [s.strip().lower() for s in section_list.split(",") if s.strip()]

        latex_parts = [r"\\documentclass{article}", r"\\usepackage[utf8]{inputenc}", f"\\title{{{title}}}", r"\\date{\\today}", r"\\begin{document}", r"\\maketitle"]

        if "introduction" in sections:
            latex_parts.append(r"\\section{Introduction}")
            latex_parts.append(intro)

        if "literature_review" in sections:
            latex_parts.append(r"\\section{Literature Review}")
            # Keep the literature review succinct: take first ~5000 chars
            lit_excerpt = knowledge if isinstance(knowledge, str) else str(knowledge)
            if len(lit_excerpt) > 5000:
                lit_excerpt = lit_excerpt[:5000] + "..."
            latex_parts.append(lit_excerpt)

        latex_parts.append(r"\\section{References}")
        sources_text = sources if isinstance(sources, str) else str(sources)
        latex_parts.append(sources_text)

        latex_parts.append(r"\\end{document}")
        latex_text = "\n".join(latex_parts)

        # Attempt to compile using the helper
        output_filename = "initial_report.pdf"
        compile_result_str = await latex_to_pdf(latex_text, output_filename)
        try:
            compile_result = json.loads(compile_result_str)
        except Exception:
            compile_result = {"status": "error", "message": "Failed to parse latex_to_pdf output."}

        # Write structured agent output so reporter can pick it up
        try:
            write_params = WriteAgentOutputInput(
                agent_id="planning_initial_report",
                agent_role="planning_initial_report",
                status="completed" if compile_result.get("status") == "success" else "partial",
                inputs={"sections": sections},
                output_files={"initial_report.pdf": os.path.join("reports", output_filename)},
                output_metrics={"latex_source": latex_text, "latex_pdf": compile_result.get("latex_pdf")},
                output_summary="Initial LaTeX generated during planning.",
                errors=[] if compile_result.get("status") == "success" else [compile_result.get("message")],
                warnings=[],
            )
            # call write_agent_output directly
            _ = await write_agent_output(write_params)
        except Exception:
            # non-fatal; continue
            pass

        log_tool_state(ToolEvent('tool_finished', 'text', TextPayload(message='Initial LaTeX generation finished.')))
        return json.dumps({"status": compile_result.get("status", "error"), "latex_text": latex_text, **compile_result})

    except Exception as e:
        log_tool_state(ToolEvent('error', 'text', TextPayload(message=str(e))))
        return json.dumps({"status": "error", "message": str(e)})
